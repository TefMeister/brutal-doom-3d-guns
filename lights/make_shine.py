# Shiny guns and gloves: the game's own lights (fires, barrels, lamps, muzzle flashes) reflect off them strongly
# (2026-10-19, Tefa: "not the distance the light starts reacting on the gun, but the strength of how much it lights up the
# weapon and how strong the reflection is on the gun").
#   python lights/make_shine.py <out pk3 folder> <skin path in game>=<skin file on disk> ...
#
# Why: the cube guns are near-black metal (34, 35, 39), so a light that falls on them multiplies a dark colour and barely
# shows. A reflection (GZDoom's specular material: per pixel, from each dynamic light, the eye and the face's normal) is
# added on top whatever the colour, which is what makes metal read as lit. Proven on the Ashes cube shotgun, flat, on
# 2026-10-08 (tools/light_probe in ashes-2063-weapons): glossiness 3 showed, 24 was a pin-point nobody could see; the
# engine only uses a specular map when a normal map is there too, so each skin gets a flat one.
# Here: SPECULAR_LEVEL twice the probe's 1.5. The map comes from the skin's own colours: grey (metal) shines fully, dark
# or not; coloured texels (wood, leather, skin, paint) a quarter.
import os
import sys

from PIL import Image

GLOSSINESS = 3.0
SPECULAR_LEVEL = 3.0        # the 2026-10-08 probe used 1.5; Tefa asked for at least twice as strong
METAL_SAT = 0.18            # above this colour saturation a texel is not metal
NON_METAL = 0.25            # how much a coloured texel still shines

out = os.path.abspath(sys.argv[1])
lines = ["// Generated by brutal-doom-3d-guns/lights/make_shine.py (Tefa 2026-10-19): shiny metal on the guns and gloves."]
for arg in sys.argv[2:]:
    game_path, disk = arg.split("=", 1)
    skin = Image.open(disk).convert("RGB")
    spec = Image.new("RGB", skin.size)
    px, sp = skin.load(), spec.load()
    for y in range(skin.size[1]):
        for x in range(skin.size[0]):
            r, g, b = px[x, y]
            hi, lo = max(r, g, b), min(r, g, b)
            sat = (hi - lo) / hi if hi else 0.0
            metal = max(0.0, min(1.0, 1.0 - sat / METAL_SAT))
            v = int(round(255 * (NON_METAL + (1.0 - NON_METAL) * metal)))
            sp[x, y] = (v, v, v)
    base = os.path.splitext(game_path)[0]
    stem = base.split("/")[-1]
    spec_path = f"models/shine/{stem}_spec.png"
    norm_path = f"models/shine/{stem}_norm.png"
    os.makedirs(os.path.join(out, "models", "shine"), exist_ok=True)
    spec.save(os.path.join(out, spec_path))
    Image.new("RGB", skin.size, (128, 128, 255)).save(os.path.join(out, norm_path))
    lines += ["", f'material texture "{game_path}"', "{", f'    normal "{norm_path}"', f'    specular "{spec_path}"',
              f"    glossiness {GLOSSINESS}", f"    specularlevel {SPECULAR_LEVEL}", "}"]
    print(f"{game_path}: {skin.size[0]}x{skin.size[1]}, shine map written")
with open(os.path.join(out, "gldefs.shine"), "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
